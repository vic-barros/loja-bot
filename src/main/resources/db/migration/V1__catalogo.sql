-- V1: catálogo da loja (categoria, produto, variacao, foto_produto)

CREATE TABLE categoria (
    categoria_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         varchar(50) NOT NULL,
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE produto (
    produto_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id  bigint        NOT NULL,
    nome          varchar(120)  NOT NULL,
    descricao     text,
    tecido        varchar(50),
    preco         numeric(10,2) NOT NULL,
    ativo         boolean       NOT NULL DEFAULT true,
    criado_em     timestamptz   NOT NULL DEFAULT now(),
    atualizado_em timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_produto_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria (categoria_id),
    CONSTRAINT ck_produto_preco CHECK (preco > 0)
);

CREATE INDEX idx_produto_categoria ON produto (categoria_id);

CREATE TABLE variacao (
    variacao_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id         bigint      NOT NULL,
    cor                varchar(40) NOT NULL,
    tamanho            varchar(10) NOT NULL,
    sku                varchar(40) NOT NULL,
    quantidade_estoque integer     NOT NULL DEFAULT 0,
    ativo              boolean     NOT NULL DEFAULT true,
    versao             bigint      NOT NULL DEFAULT 0,
    CONSTRAINT fk_variacao_produto
        FOREIGN KEY (produto_id) REFERENCES produto (produto_id),
    CONSTRAINT uk_variacao_sku UNIQUE (sku),
    CONSTRAINT uk_variacao_produto_cor_tamanho UNIQUE (produto_id, cor, tamanho),
    CONSTRAINT ck_variacao_estoque CHECK (quantidade_estoque >= 0)
);

CREATE TABLE foto_produto (
    foto_produto_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id      bigint       NOT NULL,
    cor             varchar(40),
    url             varchar(500) NOT NULL,
    ordem           integer      NOT NULL DEFAULT 0,
    CONSTRAINT fk_foto_produto_produto
        FOREIGN KEY (produto_id) REFERENCES produto (produto_id),
    CONSTRAINT uk_foto_produto_produto_ordem UNIQUE (produto_id, ordem),
    CONSTRAINT ck_foto_produto_ordem CHECK (ordem >= 0),
    CONSTRAINT ck_foto_produto_url CHECK (url LIKE 'https://%')
);